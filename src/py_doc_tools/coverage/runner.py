"""Coverage report generation."""

from __future__ import annotations

import posixpath
import sys
from typing import TYPE_CHECKING

from py_doc_tools.core.exceptions import MissingConfigSectionError
from py_doc_tools.core.subprocesses import run_command
from py_doc_tools.coverage.nav import inject_coverage_backlinks, update_coverage_nav

if TYPE_CHECKING:
    from pathlib import Path

    from py_doc_tools.config.model import DocToolsConfig
    from py_doc_tools.core.console import Console


GENERATED_MARKER = "<!-- Generated by py-doc-tools. Do not edit manually. -->"


def run_coverage(cfg: DocToolsConfig, console: Console) -> int:
    """Run pytest, generate HTML coverage, and write the MkDocs coverage page."""
    if cfg.coverage is None:
        msg = "coverage"
        raise MissingConfigSectionError(msg)

    cov_cfg = cfg.coverage
    package = cov_cfg.package or (cfg.packages[0] if cfg.packages else None)

    if package is None:
        msg = "coverage.package"
        raise MissingConfigSectionError(msg)

    output_dir = _coverage_output_dir(cfg)

    cmd = [
        sys.executable,
        "-m",
        "pytest",
        f"--cov={package}",
        "--cov-report",
        f"html:{output_dir.as_posix()}",
    ]

    if cov_cfg.branch:
        cmd.append("--cov-branch")

    if cov_cfg.quiet:
        cmd.extend(["--no-header", "-q"])

    console.info("Running coverage report.")
    proc = run_command(cmd, cwd=cfg.project_root, check=False)

    if proc.returncode == 0:
        console.ok(f"Coverage report generated: {output_dir}")
        _ = generate_coverage_page(cfg, console)
        inject_coverage_backlinks(cfg, console)
        update_coverage_nav(cfg, console)
    else:
        console.warn("Coverage command returned a non-zero exit code.")

    return proc.returncode


def generate_coverage_page(cfg: DocToolsConfig, console: Console) -> Path:
    """Generate the MkDocs page embedding the HTML coverage report."""
    if cfg.coverage is None:
        msg = "coverage"
        raise MissingConfigSectionError(msg)

    output_dir = _coverage_output_dir(cfg)
    page_file = _coverage_page_file(cfg)
    entrypoint = _find_coverage_entrypoint(output_dir, cfg.coverage.entrypoints)

    iframe_src = _mkdocs_runtime_relative_url(page_file, entrypoint)
    markdown_link = _mkdocs_source_relative_url(page_file, entrypoint)

    page_file.parent.mkdir(parents=True, exist_ok=True)

    content = f"""{GENERATED_MARKER}

# {cfg.coverage.title}

<iframe
  src="{iframe_src}"
  style="width:100%; height:80vh; border:none;"
  title="Coverage Report">
</iframe>

[Open coverage report in a new page]({markdown_link})
"""

    _ = page_file.write_text(content, encoding="utf-8")
    console.ok(f"Coverage documentation page generated: {page_file}")

    return page_file


def _coverage_output_dir(cfg: DocToolsConfig) -> Path:
    if cfg.coverage is None:
        msg = "coverage"
        raise MissingConfigSectionError(msg)

    if cfg.coverage.output_dir is not None:
        return cfg.coverage.output_dir

    return cfg.docs_src_dir / "coverage"


def _coverage_page_file(cfg: DocToolsConfig) -> Path:
    if cfg.coverage is None:
        msg = "coverage"
        raise MissingConfigSectionError(msg)

    if cfg.coverage.page_file is not None:
        return cfg.coverage.page_file

    return cfg.docs_src_dir / "coverage-report.md"


def _find_coverage_entrypoint(
    output_dir: Path,
    entrypoints: list[str],
) -> Path:
    """Find the HTML entrypoint generated by coverage.py."""
    for entrypoint in entrypoints:
        candidate = output_dir / entrypoint
        if candidate.exists():
            return candidate

    expected = ", ".join(entrypoints)
    message = (
        "Coverage HTML report entrypoint was not found. "
        f"Expected one of: {expected}. "
        f"Coverage output directory: {output_dir}"
    )
    raise FileNotFoundError(message)


def _mkdocs_source_relative_url(page_file: Path, target_file: Path) -> str:
    """Build a source-relative URL for MkDocs Markdown link validation.

    MkDocs validates Markdown links relative to the source Markdown file
    location inside the docs directory.

    Example:
        docs/coverage-report.md -> docs/coverage/index.html
        gives: coverage/index.html
    """
    return posixpath.relpath(
        target_file.as_posix(),
        start=page_file.parent.as_posix(),
    )


def _mkdocs_runtime_relative_url(page_file: Path, target_file: Path) -> str:
    """Build a runtime-relative URL for raw HTML elements.

    MkDocs serves a Markdown page like ``coverage-report.md`` as
    ``coverage-report/index.html`` when directory URLs are enabled.

    Raw HTML attributes such as iframe ``src`` are not rewritten by MkDocs,
    so they must be relative to the generated page URL directory.
    """
    page_url_dir = page_file.with_suffix("")
    return posixpath.relpath(
        target_file.as_posix(),
        start=page_url_dir.as_posix(),
    )
