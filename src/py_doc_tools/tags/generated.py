"""Generated source tag formatting and detection."""

from __future__ import annotations

import re
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from py_doc_tools.issues.model import DiagnosticIssue


GENERATED_TAG_LINE_PATTERN = re.compile(
    r"^\s*#\s*(?:TODO|FIXME)\[py-doc-tools:[^\]]+\]:.*$",
    re.IGNORECASE,
)

LEGACY_GENERATED_TAG_LINE_PATTERNS = (
    re.compile(r"^\s*#\s*FIXME\[Ruff:[^\]]+\]:.*$", re.IGNORECASE),
    re.compile(r"^\s*#\s*TODO\[Ruff:[^\]]+\]:.*$", re.IGNORECASE),
    re.compile(r"^\s*#\s*FIXME\[BasedPyright:[^\]]+\]:.*$", re.IGNORECASE),
    re.compile(r"^\s*#\s*TODO\[BasedPyright:[^\]]+\]:.*$", re.IGNORECASE),
    re.compile(r"^\s*#\s*FIXME\[MkDocs:[^\]]+\]:.*$", re.IGNORECASE),
    re.compile(r"^\s*#\s*TODO\[MkDocs:[^\]]+\]:.*$", re.IGNORECASE),
    re.compile(
        r"^\s*#\s*(?:TODO|FIXME)\s*\[MKDOC\]\s*\[[^\]]+\].*$",
        re.IGNORECASE,
    ),
)


def render_generated_tag(
    issue: DiagnosticIssue,
    *,
    prefix: str = "py-doc-tools",
) -> str:
    """Render an auto-generated source tag for one diagnostic issue.

    Args:
        issue: Diagnostic issue to render.
        prefix: Prefix used to identify tags generated by py-doc-tools.

    Returns:
        Single-line Python comment containing the diagnostic tag.
    """
    marker = _marker_for_issue(issue)
    source = issue.source
    code = issue.code or "UNKNOWN"
    message = _sanitize_tag_message(issue.message)

    return f"# {marker}[{prefix}:{source}:{code}]: {message}"


def _sanitize_tag_message(message: str) -> str:
    r"""Sanitize a diagnostic message before injecting it into Python source.

    Args:
        message: Raw diagnostic message.

    Returns:
        Single-line message safe to inject in Python source comments.

    Example:
        ```python
        assert _sanitize_tag_message(r"a\b.py") == "a/b.py"
        ```
    """
    return message.strip().replace("\n", " ").replace("\\", "/")


def is_generated_tag_line(line: str, *, clean_legacy: bool = True) -> bool:
    """Return whether a line is an automatically generated source tag.

    Args:
        line: Source line to inspect.
        clean_legacy: If ``True``, also detect legacy tags generated before the
            unified ``py-doc-tools`` prefix.

    Returns:
        ``True`` when the line is recognized as generated by py-doc-tools or by
        a legacy documentation/lint tagging script.
    """
    normalized = line.rstrip("\r\n")

    if GENERATED_TAG_LINE_PATTERN.search(normalized):
        return True

    if not clean_legacy:
        return False

    return any(
        pattern.search(normalized) for pattern in LEGACY_GENERATED_TAG_LINE_PATTERNS
    )


def _marker_for_issue(issue: DiagnosticIssue) -> str:
    if issue.severity == "todo":
        return "TODO"

    return "FIXME"
